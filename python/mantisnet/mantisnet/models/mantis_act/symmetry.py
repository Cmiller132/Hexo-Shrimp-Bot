# The coarse_distance_axis ablation (§29 `full_coarse_geometry`)


def coarse_relation_count(d_max: int = 12) -> int:
    """Class count of the coarse scheme: on-axis and off-axis per bucket."""
    if d_max < 1:
        raise ValueError(f"d_max must be at least 1, got {d_max}")
    return 2 * d_max


def coarse_relation(dq, dr, d_max: int = 12) -> np.ndarray:
    """The pre-orbit relation scheme: distance bucket plus on/off-axis.

    The bucket is ``min(d, d_max) - 1``, clamping at the last bucket the way
    the distance buckets of the older representation do, and it doubles for
    whether the displacement lies on an axis. *Which* axis is not part of the
    class: that is the §11.3 route, and folding it in would make the class
    depend on absolute axis identity and stop being D6-invariant. A caller
    needing SELF or PAD ids places them above :func:`coarse_relation_count`;
    the reserved ids of §11.2 belong to the orbit id space, not this one.
    """
    if d_max < 1:
        raise ValueError(f"d_max must be at least 1, got {d_max}")
    dq = np.asarray(dq, dtype=np.int64)
    dr = np.asarray(dr, dtype=np.int64)
    distance = hex_distance(dq, dr)
    if (distance < 1).any():
        raise ValueError("displacement (0, 0) has no coarse relation class")
    bucket = np.minimum(distance, d_max) - 1
    return (2 * bucket + (on_axis(dq, dr) < 0)).astype(np.int64, copy=False)
